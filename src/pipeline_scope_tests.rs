use super::*;
use crate::report::SmellKind;
use std::fs;

const CHAIN: &str =
    "export function country(invoice: any) {\n  return invoice.customer.profile.address.region.country.code;\n}\n";

const CLONE: &str = "export function handler(a: number, b: number) {\n  const d = moduleA.run(b, 'alpha');\n  const e = moduleC.run(a, 'beta');\n  const f = moduleD.merge(d, e, 'gamma');\n  return moduleE.finish(f, d, e);\n}\n";

fn write(dir: &Path, rel: &str, body: &str) {
    let path = dir.join(rel);
    fs::create_dir_all(path.parent().unwrap()).unwrap();
    fs::write(path, body).unwrap();
}

fn smells_in(report: &AnalysisReport, suffix: &str) -> Vec<SmellKind> {
    report
        .smells
        .iter()
        .filter(|finding| finding.file.ends_with(suffix))
        .map(|finding| finding.kind)
        .collect()
}

fn cloned_files(report: &AnalysisReport, dir: &Path) -> Vec<String> {
    let mut files: Vec<String> = report
        .duplication
        .iter()
        .flat_map(|class| &class.occurrences)
        .map(|occurrence| {
            occurrence
                .file
                .strip_prefix(dir)
                .unwrap()
                .to_string_lossy()
                .into_owned()
        })
        .collect();
    files.sort();
    files.dedup();
    files
}

fn cycle_count(report: &AnalysisReport, dir_name: &str) -> usize {
    report
        .cycles
        .iter()
        .filter(|cycle| {
            cycle
                .edges
                .iter()
                .all(|edge| edge.file.to_string_lossy().contains(dir_name))
        })
        .count()
}

#[test]
fn test_files_are_skipped_by_smells_unless_included() {
    let tmp = tempfile::tempdir().unwrap();
    let dir = tmp.path();
    write(dir, "src/__tests__/a.test.tsx", CHAIN);
    write(dir, "src/lib/x.ts", CHAIN);

    let (report, _) = analyze_path(dir, None).unwrap();
    assert!(smells_in(&report, "src/lib/x.ts").contains(&SmellKind::MessageChain));
    assert!(smells_in(&report, "a.test.tsx").is_empty());
    assert_eq!(report.meta.smells_skipped.tests, 1);

    write(dir, "sensez.toml", "[smells]\ninclude_tests = true\n");
    let (report, _) = analyze_path(dir, None).unwrap();
    assert!(smells_in(&report, "a.test.tsx").contains(&SmellKind::MessageChain));
}

#[test]
fn baseline_test_layouts_count_as_tests_not_config_excludes() {
    let tmp = tempfile::tempdir().unwrap();
    let dir = tmp.path();
    write(dir, "test/helpers.ts", CHAIN);
    write(dir, "pkg/test_util.py", "def util():\n    return 1\n");

    let (report, _) = analyze_path(dir, None).unwrap();
    assert_eq!(
        report.meta.smells_skipped.tests, 2,
        "{:?}",
        report.meta.smells_skipped
    );
    assert_eq!(
        report.meta.smells_skipped.config_exclude, 0,
        "{:?}",
        report.meta.smells_skipped
    );
}

#[test]
fn generated_files_are_not_graph_or_local_smell_hotspots() {
    let tmp = tempfile::tempdir().unwrap();
    let dir = tmp.path();
    write(dir, "package.json", "{}\n");
    write(dir, "src/__generated__/sdk.ts", "export const sdk = 1;\n");
    write(dir, "src/core/util.ts", "export const util = 1;\n");
    write(
        dir,
        "src/lib/header.ts",
        &format!("// @generated by codegen\n{CHAIN}"),
    );
    for n in 0..6 {
        write(
            dir,
            &format!("src/pages/p{n}.ts"),
            "import { sdk } from '../__generated__/sdk';\nimport { util } from '../core/util';\nexport const v = sdk + util;\n",
        );
    }

    let (report, _) = analyze_path(dir, None).unwrap();
    assert!(smells_in(&report, "src/__generated__/sdk.ts").is_empty());
    assert!(smells_in(&report, "src/lib/header.ts").is_empty());
    assert!(smells_in(&report, "src/core/util.ts").contains(&SmellKind::ShotgunSurgeryHazard));
    assert_eq!(report.meta.smells_skipped.generated, 2);
}

#[test]
fn test_importers_do_not_count_as_fan_in() {
    let tmp = tempfile::tempdir().unwrap();
    let dir = tmp.path();
    write(dir, "package.json", "{}\n");
    write(dir, "src/core/util.ts", "export const util = 1;\n");
    let importer = "import { util } from '../core/util';\nexport const v = util;\n";
    for n in 0..3 {
        write(dir, &format!("src/pages/p{n}.ts"), importer);
        write(dir, &format!("src/__tests__/t{n}.test.ts"), importer);
        write(dir, &format!("src/__mocks__/m{n}.ts"), importer);
    }

    let (report, _) = analyze_path(dir, None).unwrap();
    assert!(smells_in(&report, "src/core/util.ts").is_empty());

    write(dir, "sensez.toml", "[smells]\ninclude_tests = true\n");
    let (report, _) = analyze_path(dir, None).unwrap();
    assert!(smells_in(&report, "src/core/util.ts").contains(&SmellKind::ShotgunSurgeryHazard));
}

#[test]
fn duplication_skips_test_and_generated_copies() {
    let tmp = tempfile::tempdir().unwrap();
    let dir = tmp.path();
    for rel in [
        "src/__tests__/a.ts",
        "src/lib/x.test.ts",
        "src/__generated__/sdk.ts",
        "src/lib/routes.gen.ts",
        "src/__mocks__/api.ts",
        "src/lib/testing-utils.ts",
        "src/versions/format.ts",
    ] {
        write(dir, rel, CLONE);
    }
    write(
        dir,
        "src/lib/hdr.ts",
        &format!("// This file was automatically generated. DO NOT EDIT.\n{CLONE}"),
    );
    write(dir, "sensez.toml", "[duplication]\nthreshold = 20\n");

    let (report, _) = analyze_path(dir, None).unwrap();
    assert_eq!(
        cloned_files(&report, dir),
        ["src/lib/testing-utils.ts", "src/versions/format.ts"]
    );
    assert_eq!(report.meta.duplication_skipped.tests, 3);
    assert_eq!(report.meta.duplication_skipped.generated, 3);
    assert!(reporter::render(&report, false).contains("skipped 3 test, 3 generated"));

    write(
        dir,
        "sensez.toml",
        "[duplication]\nthreshold = 20\ninclude_tests = true\ninclude_generated = true\n",
    );
    let (report, _) = analyze_path(dir, None).unwrap();
    assert_eq!(cloned_files(&report, dir).len(), 8);
}

#[test]
fn test_cycles_are_reported_unless_explicitly_excluded() {
    let tmp = tempfile::tempdir().unwrap();
    let dir = tmp.path();
    for folder in ["tests", "migrations"] {
        write(
            dir,
            &format!("{folder}/h1.ts"),
            "import { b } from './h2';\nexport const a = b;\n",
        );
        write(
            dir,
            &format!("{folder}/h2.ts"),
            "import { a } from './h1';\nexport const b = a;\n",
        );
    }

    let (report, _) = analyze_path(dir, None).unwrap();
    assert_eq!(cycle_count(&report, "/tests/"), 1);
    assert_eq!(cycle_count(&report, "/migrations/"), 0);

    write(
        dir,
        "sensez.toml",
        "[cycles]\nexclude = [\"**/tests/**\"]\n",
    );
    let (report, _) = analyze_path(dir, None).unwrap();
    assert_eq!(cycle_count(&report, "/tests/"), 0);
}
