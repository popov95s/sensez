//! Per-language smell thresholds and toggles.

use crate::report::{ActionLevel, SmellKind};
use serde::{Deserialize, Serialize};
use std::collections::BTreeMap;

#[derive(Debug, Clone, Copy, Hash, Serialize, Deserialize, PartialEq, Eq)]
#[serde(rename_all = "snake_case")]
pub enum Strictness {
    Low,
    Medium,
    High,
}

#[derive(Debug, Clone, Hash, Serialize, Deserialize)]
#[serde(default)]
pub struct Smells {
    pub enabled: bool,
    pub exclude: Vec<String>,
    pub disabled: Vec<SmellKind>,
    #[serde(skip)]
    pub actions: BTreeMap<SmellKind, ActionLevel>,
    pub max_cyclomatic: usize,
    pub max_cognitive: usize,
    pub max_function_lines: usize,
    pub max_nesting: usize,
    pub max_params: usize,
    pub max_returns: usize,
    pub count_guard_clauses: bool,
    pub max_class_methods: usize,
    pub max_chain_depth: usize,
    pub message_chain_ignore_roots: Vec<String>,
    pub max_wrapper_depth: usize,
    pub data_clump_min_fields: usize,
    pub data_clump_min_occurrences: usize,
    pub sibling_helper_min_similarity: usize,
    pub sibling_helper_min_lexemes: usize,
    pub shotgun_blast_threshold: usize,
    pub god_module_fan: usize,
    pub god_module_min_fan_in: usize,
    pub god_module_min_fan_out: usize,
    pub god_module_min_lines: usize,
    pub god_module_min_units: usize,
    pub magic_numbers: bool,
    pub magic_number_ignore: Vec<String>,
    pub magic_number_ignore_array_indexes: bool,
    pub magic_number_ignore_default_values: bool,
    pub magic_number_allow_http_status: bool,
    pub narrating_code: bool,
    pub min_comment_lines: usize,
    pub max_comment_ratio_percent: usize,
    pub narrating_min_function_lines: usize,
    pub cyclomatic_complexity: bool,
    pub long_function: bool,
    pub large_class: bool,
    pub long_parameter_list: bool,
    pub too_many_returns: bool,
    pub split_variable: bool,
    pub split_variable_min_assigns: usize,
    pub loose_typing: bool,
    pub loose_typing_strictness: Strictness,
    pub magic_string_default: bool,
    pub magic_string_default_strictness: Strictness,
    pub nested_ternary_strictness: Strictness,
    pub swallowed_error_strictness: Strictness,
    pub mocked_subject_strictness: Strictness,
    pub repeated_iteration_include_tests: bool,
    pub max_bool_params: usize,
    pub tuple_packing: bool,
    pub max_tuple_return: usize,
    pub tuple_allow_homogeneous: bool,
    pub param_mutation: bool,
    pub param_attr_mutation: bool,
    pub param_reassignment: bool,
    pub implicit_schema_min_keys: usize,
    pub literal_membership: bool,
    pub literal_membership_skip_external_vocab: bool,
    pub max_nested_function_lines: usize,
    pub nested_function_skip_capturing: bool,
    pub assertion_functions: Vec<String>,
    pub n_plus_one_callees: Vec<String>,
    pub n_plus_one_max_constant_bound: usize,
    pub n_plus_one_await_in_loop: bool,
    pub dependency_reimplementation_providers: Vec<String>,
    #[serde(skip)]
    pub compiled: super::compiled::Compiled,
}

